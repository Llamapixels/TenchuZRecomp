#!/usr/bin/env python3
"""Find function addresses materialized from `lis`+`addi`/`ori` immediate pairs.

The .rdata/.data pointer-table scan (derive_fnptr_targets.py) misses functions
whose address never appears contiguously in memory. The PPC compiler often
materializes a function address as:

    lis   rD, hi16        (addis rD, 0, hi16)
    addi  rD, rD, lo16    (or ori rD, rD, lo16)

so the 32-bit value exists only as instruction immediates. This scanner
reconstructs such values and keeps those that point into the executable code
range and are not already-known function starts.

Usage:
    python scan_lis_addi_fnptr.py --image <decrypted.bin> --init <init.cpp>
                                  --out <entries.toml>
"""
from __future__ import annotations

import argparse
import re
import struct

BASE = 0x82000000

EXEC_SECTIONS = [
    (".text", 0x82270000, 0x599DDC),
    (".embsec_a", 0x82809E00, 0x99AC),
    (".embsec_b", 0x82813800, 0xA4B8),
    (".embsec_c", 0x8281DE00, 0x1D0C),
    (".embsec_d", 0x8281FC00, 0x5C80),
    (".embsec_e", 0x82825A00, 0x1350),
    (".embsec_f", 0x82826E00, 0xCC8),
    (".embsec_g", 0x82827C00, 0x21B8),
]


def sign16(v: int) -> int:
    return v - 0x10000 if v & 0x8000 else v


def load_known(path: str) -> set[int]:
    known = set()
    for line in open(path, errors="ignore"):
        m = re.match(r"\s*\{\s*0x([0-9A-Fa-f]{8})\s*,", line)
        if m:
            known.add(int(m.group(1), 16))
    return known


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--image", required=True)
    ap.add_argument("--init", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--window", type=int, default=6,
                    help="max instructions between lis and the lo half")
    args = ap.parse_args()

    data = open(args.image, "rb").read()
    known = load_known(args.init)
    code_lo = min(va for _, va, _ in EXEC_SECTIONS)
    code_hi = max(va + sz for _, va, sz in EXEC_SECTIONS)

    # Parse every exec section as an instruction stream.
    instrs: list[tuple[int, int]] = []
    for _name, va, size in EXEC_SECTIONS:
        for off in range(0, size, 4):
            instrs.append((va + off, struct.unpack_from(">I", data, va - BASE + off)[0]))

    candidates: dict[int, str] = {}
    for i, (va, w) in enumerate(instrs):
        if (w >> 26) != 15:  # addis
            continue
        rD = (w >> 21) & 31
        rA = (w >> 16) & 31
        if rA != 0:
            continue
        hi = w & 0xFFFF
        for j in range(i + 1, min(i + 1 + args.window, len(instrs))):
            v2, w2 = instrs[j]
            op2 = w2 >> 26
            if op2 == 14:  # addi
                if ((w2 >> 21) & 31) == rD and ((w2 >> 16) & 31) == rD:
                    value = ((hi << 16) + sign16(w2 & 0xFFFF)) & 0xFFFFFFFF
                    break
            elif op2 == 24:  # ori
                if ((w2 >> 21) & 31) == rD and ((w2 >> 16) & 31) == rD:
                    value = ((hi << 16) | (w2 & 0xFFFF)) & 0xFFFFFFFF
                    break
            elif op2 == 14:
                pass
        else:
            continue
        if code_lo <= value < code_hi and value not in known:
            candidates.setdefault(value, f"0x{va:08X}")

    lines = [
        "# Auto-generated by tools/scan_lis_addi_fnptr.py -- do not edit by hand.",
        f"# {len(candidates)} lis+addi/ori materialized code addresses "
        f"(not already known)",
    ]
    lines += [f"0x{a:08X} = {{ name = \"fnptr_{a:08X}\" }}"
              for a in sorted(candidates)]
    open(args.out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"candidates: {len(candidates)}")
    for probe in (0x824805B0,):
        print(f"  contains 0x{probe:08X}: {probe in candidates}")


if __name__ == "__main__":
    main()
