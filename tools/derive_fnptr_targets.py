#!/usr/bin/env python3
"""Derive manifest `[functions]` entries for data-referenced function pointers.

Why this exists
---------------
The ReXGlue codegen discovers functions from:
  * control flow (`bl` call targets, `b` branch targets),
  * ``.pdata`` exception unwind entries, and
  * MSVC RTTI vtables (needs Complete Object Locators).

This title has **no** MSVC RTTI, so the vtable pass finds nothing, and any
function reachable *only* through a function-pointer table (mostly in
``.rdata``) is never registered. When the recompiled code later performs an
indirect call through one of those tables it hits:

    [FATAL] Call to invalid or unregistered function at guest address 0x.........

The fix applied to this project is declarative: list every such address under
``[entrypoint.functions]`` in ``tenchuz_manifest.toml`` so codegen registers it as
a CONFIG entry point. This script derives that list.

Method
------
1. Take the decrypted guest image: the loaded XEX image from guest memory
   (base 0x82000000), saved as tools/tenchuz_decrypted.bin. It is game code,
   so it is never part of the repository.
2. Take the section table from a verbose codegen run
   (``rexglue -v codegen tenchuz_manifest.toml --ignore-stamp``); the section
   lines look like:
       BinaryView: section '.rdata' at 0x82000600 size 0xE82A8 exec=false
3. Code range = [min start of exec sections, max end of exec sections).
4. Read the already-known function starts out of the generated
   ``generated/default/tenchuz_init.cpp`` function table.
5. Scan every *non-executable* section for 4-byte-aligned big-endian (PowerPC)
   values inside the code range. Any value that is not an already-known function
   start is a candidate target.

Sanity: random 32-bit noise would land on a specific unknown function start
with probability ~1e-6, so the false-positive rate is dominated by genuinely
referenced addresses. All candidates were additionally verified to disassemble
to a valid function terminator (blr / b / bctr).
"""

from __future__ import annotations

import argparse
import re
import struct
import sys

SECTION_RE = re.compile(
    r"BinaryView: section '(?P<name>[^']+)' at 0x(?P<va>[0-9A-Fa-f]+) "
    r"size 0x(?P<size>[0-9A-Fa-f]+) exec=(?P<exec>true|false)"
)
KNOWN_RE = re.compile(r"\{\s*0x([0-9A-Fa-f]{8})\s*,")


def parse_sections(trace_path: str):
    sections = []
    with open(trace_path, "r", errors="ignore") as fh:
        for line in fh:
            m = SECTION_RE.search(line)
            if m:
                sections.append(
                    (
                        m.group("name"),
                        int(m.group("va"), 16),
                        int(m.group("size"), 16),
                        m.group("exec") == "true",
                    )
                )
    if not sections:
        sys.exit(f"no section lines found in {trace_path}")
    return sections


def parse_known(init_path: str):
    known = set()
    with open(init_path, "r", errors="ignore") as fh:
        for line in fh:
            m = KNOWN_RE.search(line)
            if m:
                known.add(int(m.group(1), 16))
    if not known:
        sys.exit(f"no function entries found in {init_path}")
    return known


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--image", required=True, help="decrypted guest image dump")
    ap.add_argument("--init", required=True, help="generated <app>_init.cpp")
    ap.add_argument("--trace", required=True, help="`rexglue -v codegen` stdout")
    ap.add_argument("--base", default="0x82000000", help="image base address")
    ap.add_argument("--out", help="write TOML entries here (default: stdout)")
    args = ap.parse_args()

    base = int(args.base, 16)
    data = open(args.image, "rb").read()
    sections = parse_sections(args.trace)
    known = parse_known(args.init)

    exec_secs = [s for s in sections if s[3]]
    code_lo = min(va for _, va, _, _ in exec_secs)
    code_hi = max(va + size for _, va, size, _ in exec_secs)

    def u32(va: int) -> int:
        return struct.unpack_from(">I", data, va - base)[0]

    targets: set[int] = set()
    per_section: list[tuple[str, int]] = []
    for name, va, size, is_exec in sections:
        if is_exec:
            continue
        count = 0
        for off in range(0, size - 3, 4):
            value = u32(va + off)
            if (value & 3) == 0 and code_lo <= value < code_hi and value not in known:
                targets.add(value)
                count += 1
        if count:
            per_section.append((name, count))

    out_lines = [
        "# Auto-generated by tools/derive_fnptr_targets.py -- do not edit by hand.",
        f"# code range 0x{code_lo:08X}..0x{code_hi:08X}; {len(targets)} targets",
        *[f"#   {name}: {count} refs" for name, count in per_section],
    ]
    out_lines += [f"0x{t:08X} = {{ name = \"fnptr_{t:08X}\" }}" for t in sorted(targets)]
    text = "\n".join(out_lines) + "\n"

    if args.out:
        open(args.out, "w", newline="\n").write(text)
        print(f"wrote {len(targets)} targets to {args.out}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    print(f"sections={len(sections)} known={len(known)} targets={len(targets)}",
          file=sys.stderr)


if __name__ == "__main__":
    main()
