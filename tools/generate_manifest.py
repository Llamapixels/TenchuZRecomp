#!/usr/bin/env python3
"""Merge the manifest base with the derived function-boundary lists.

Inputs (all under tools/):
  * tenchuz_manifest.base.toml  -- [project]/[entrypoint] + hand-recorded thunks
  * fnptr_entries.toml          -- data-referenced targets (derive_fnptr_targets.py)
  * extra_entries.toml          -- Unresolved* targets + runtime fatal addresses
  * entry_points_keep.toml     -- optional override: never drop these addresses

Output:
  * ../tenchuz-recomp/tenchuz_manifest.toml
  * ../logs/manifest_dropped_labels.txt -- audit trail of everything filtered out

The merged file keeps a single `[entrypoint.functions]` table. Duplicate
addresses are collapsed (the base file wins for its explicit thunk names).

Intra-function labels are filtered out
--------------------------------------
The derived lists mix two very different things: real function starts (many of
them leaf functions that this image's `.pdata` omits) and intra-function labels
(loop heads, jump-table cases, call return points) that merely *look* like code
addresses when `.rdata`/`.text` is scanned for code-range words.

Registering a label is not benign. `FunctionGraph::classifyTarget`
(src/codegen/function_graph.cpp) tests "is a registered entry point" *before*
"is inside the caller's function", so every `b`/`bc` to a registered label is
emitted as a conditional *tail call* instead of `goto loc_XXXX`
(context.cpp:emit_conditional_branch). The split-off body still carries the
enclosing function's epilogue, so it pops a guest frame it never pushed:
ctx.r1 drifts and every `__restgprlr_*` restores garbage callee-saved
registers (the "read of guest 0x1A4 with a null `this`" crash class).

tools/classify_entry_points.py tells the two apart: a real function can only be
*entered by a branch*, never fallen into, so the instruction before it is a
terminator (`b`/`blr`/`bctr`/`bclr`/branch-always). Entries whose predecessor
is a fall-through, a conditional branch, or a `bl`/`bctrl` return point are
labels and are dropped here.

If dropping an entry makes the runtime report
`[FATAL] Call to invalid or unregistered function at guest address 0x...`, that
address really is an indirect-call target: add it to tools/entry_points_keep.toml
(that is the safe way -- a keep-listed address with no branch targeting it
emits no tail call) and record the reason there.

Usage:
    python tools/generate_manifest.py
"""
from __future__ import annotations

import os
import re

import classify_entry_points as cep

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.join(HERE, "tenchuz_manifest.base.toml")
FNPTR = os.path.join(HERE, "fnptr_entries.toml")
EXTRA = os.path.join(HERE, "extra_entries.toml")
KEEP = os.path.join(HERE, "entry_points_keep.toml")
# Auto-generated by tools/scan_adjustor_thunks.py: MSVC adjustor thunks
# (.pdata-less 2-insn `addi r3,r3,N; b target`) plus their .pdata-less
# targets, each verified (hard-terminator predecessor, no conditional branch
# targeting, real function-start target). Used as a source *and* folded into
# the keep set: classify_entry_points calls every one of them LABEL.
THUNKS = os.path.join(HERE, "..", "logs", "adjustor_thunks_keep.toml")
# Auto-generated by tools/scan_vtable_thunks.py: 296 16-byte virtual-method
# dispatch thunks (`lwz r12,0(r3); lwz r11,N(r12); mtspr CTR,r11; bctr`) laid
# out consecutively.  .pdata folds each whole run into one range owned by the
# preceding function, so classify_entry_points calls every thunk after the
# first a LABEL; they are real, independently-callable entry points (reached
# only via bctr from a vtable slot).  Used as a source *and* folded into the
# keep set, exactly like THUNKS above.
VTHUNKS = os.path.join(HERE, "..", "logs", "vtable_thunks_keep.toml")
# Auto-generated by tools/scan_fnptr_args.py --emit: .pdata-less callbacks
# whose address is materialised in code (`lis rS,hi; addi rD,rS,lo`) and
# passed as an argument to a registered function. Every entry was vetted by
# tools/verify_fnptr_candidates.py (terminator predecessor, not an interior
# label) and tools/check_branch_targets.py (no conditional branch targets
# it). Added LAST in the source list so hand-named entries from other files
# keep their names; this file only contributes fresh addresses.
FNPTR_ARGS = os.path.join(HERE, "fnptr_args_entries.toml")
OUT = os.path.join(HERE, "..", "tenchuz-recomp", "tenchuz_manifest.toml")
DROPPED_LOG = os.path.join(HERE, "..", "logs", "manifest_dropped_labels.txt")

ENTRY_RE = re.compile(r"^(0x[0-9A-Fa-f]{8})\s*=\s*(\{.*\})\s*$")


def read_entries(path: str) -> list[tuple[int, str]]:
    out: list[tuple[int, str]] = []
    if not os.path.exists(path):
        return out
    for line in open(path, encoding="utf-8"):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        # Strip inline comments outside of braces
        # naive: cut at # if } appears before or just after body
        # easier: try to extract body up to matching }
        m = re.match(r'^(0x[0-9A-Fa-f]{8})\s*=\s*(\{[^}]*\})', s)
        if m:
            out.append((int(m.group(1), 16), m.group(2)))
            continue
        m = ENTRY_RE.match(s)
        if m:
            out.append((int(m.group(1), 16), m.group(2)))
    return out


def main() -> None:
    base_raw = open(BASE, encoding="utf-8").read().rstrip("\n")

    # Keep only the header (everything up to and including the
    # `[entrypoint.functions]` line); the entries are re-emitted below.
    marker = "[entrypoint.functions]"
    idx = base_raw.index(marker)
    base = base_raw[: idx + len(marker)]

    keep = {addr for addr, _ in read_entries(KEEP)}
    keep |= {addr for addr, _ in read_entries(THUNKS)}  # pre-verified thunks
    keep |= {addr for addr, _ in read_entries(VTHUNKS)}  # vtable dispatch thunks
    # scan_fnptr_args.py candidates: code-materialised callback addresses,
    # each vetted by verify_fnptr_candidates.py (terminator predecessor, not
    # an interior label) and check_branch_targets.py (0 risky). They sit
    # inside .pdata function ranges (the usual absorbed-leaf phenomenon), so
    # the LABEL filter would drop them without this fold.
    keep |= {addr for addr, _ in read_entries(FNPTR_ARGS)}
    image = cep.load_image()
    pdata = cep.pdata_starts(image)
    # Conditional-branch targets cannot be function starts even when a data
    # pointer references them (a `bc` jumps into the middle of another
    # function). Computed once; passed to classify() for pointer entries.
    cond_targets = cep.conditional_branch_targets(image)

    merged: dict[int, str] = {}
    order: list[int] = []
    for addr, body in read_entries(BASE):
        if addr not in merged:
            order.append(addr)
        merged[addr] = body  # base definitions win

    # sources: (label, path, is_pointer)
    # is_pointer=True marks files whose addresses are literal 32-bit function
    # pointers in .rdata/.data (vtables, callback tables): those are *proven
    # callable*, so a terminator predecessor lets them override the
    # ".pdata range -> LABEL" rule (see classify_entry_points.classify).
    sources = [("fnptr_entries.toml", FNPTR, True),
               ("extra_entries.toml", EXTRA, False),
               ("logs/adjustor_thunks_keep.toml", THUNKS, False),
               ("logs/vtable_thunks_keep.toml", VTHUNKS, False),
               ("fnptr_args_entries.toml", FNPTR_ARGS, False)]
    counts = {}
    dropped: list[tuple[int, str, str, str]] = []
    for label, path, is_pointer in sources:
        n = 0
        for addr, body in read_entries(path):
            if addr in merged:
                continue
            if cep.TEXT_LO <= addr < cep.TEXT_HI and addr not in keep:
                kind, why = cep.classify(image, addr, pdata,
                                         is_pointer=is_pointer,
                                         cond_targets=cond_targets)
                if kind == "LABEL":
                    dropped.append((addr, label, body, why))
                    continue
            merged[addr] = body
            order.append(addr)
            n += 1
        counts[label] = n

    lines = [base, ""]
    lines.append(f"# intra-function labels filtered out: {len(dropped)} "
                 f"(see logs/manifest_dropped_labels.txt)")
    for label, _, _ in sources:
        lines.append(f"# merged from {label}: {counts[label]} new entries")
    lines.append("")
    lines += [f"0x{a:08X} = {merged[a]}" for a in order]
    lines.append("")

    out_path = os.path.normpath(OUT)
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))

    log_path = os.path.normpath(DROPPED_LOG)
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    with open(log_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# entry points dropped by tools/generate_manifest.py\n"
                "# kind=LABEL: control falls into the address (or it is a call\n"
                "# return point), so the address is an intra-function label, not\n"
                "# a function start.\n")
        for addr, label, body, why in sorted(dropped):
            f.write(f"0x{addr:08X} = {body}   # {label}: {why}\n")

    print(f"wrote {out_path}")
    print(f"total entrypoint.functions entries: {len(order)}")
    for label, _, _ in sources:
        print(f"  + {counts[label]:4d} from {label}")
    print(f"  - {len(dropped):4d} intra-function labels dropped "
          f"(-> {log_path})")


if __name__ == "__main__":
    main()
